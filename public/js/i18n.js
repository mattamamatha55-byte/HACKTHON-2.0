let currentLang = 'en';

function t(key) {
  if (translations[currentLang] && translations[currentLang][key]) {
    return translations[currentLang][key];
  }
  if (translations['en'][key]) {
    return translations['en'][key];
  }
  return key;
}

function setLanguage(langCode) {
  if (!LANGUAGES[langCode]) return;
  currentLang = langCode;
  document.documentElement.lang = langCode;

  // Update elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      el.textContent = t(key);
    }
  });

  // Update elements with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) {
      el.placeholder = t(key);
    }
  });

  // Update Language dropdowns if present
  const langSelect = document.getElementById('langSelect');
  if (langSelect) langSelect.value = langCode;

  const aiVoiceLangSelect = document.getElementById('aiVoiceLangSelect');
  if (aiVoiceLangSelect) aiVoiceLangSelect.value = langCode;

  // Emit event to notify charts and app components
  if (window.onLanguageChanged && typeof window.onLanguageChanged === 'function') {
    window.onLanguageChanged(currentLang);
  }
}

window.i18n = {
  t,
  setLanguage,
  LANGUAGES,
  get currentLang() { return currentLang; },
  translations
};
